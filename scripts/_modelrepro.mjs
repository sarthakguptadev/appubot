import { readFileSync } from 'node:fs';
import WebSocket from 'ws';
import { GatewayClient } from '@appubot/client';
const [devfile, pick] = process.argv.slice(2);
const devinfo = JSON.parse(readFileSync(devfile, 'utf8'));
const t0 = Date.now(); const log = (...a) => console.log(((Date.now() - t0) / 1000).toFixed(1).padStart(5) + 's', ...a);
const c = new GatewayClient({ baseUrl: devinfo.url, token: devinfo.token, device: { id: 'desktop', name: 'repro', platform: 'desktop', appVersion: '0.1.0' }, WebSocketImpl: WebSocket, callTimeoutMs: 120_000 });
await new Promise((res) => { c.onState((s) => { if (s === 'connected') res(); }); c.connect(); });
const [bot] = await c.call('bots.list', {});
const threads = await c.call('threads.list', {});
const th = threads[0];
log('thread', th.id, 'model', th.modelId);
c.on('thread.updated', (t) => { if (t.id === th.id) log('thread.updated model=', t.modelId, 'status=', t.status); });
const done = new Promise((res) => c.on('message.completed', res));
const r = await c.call('threads.setModel', { id: th.id, modelId: pick });
log('setModel ->', r.modelId);
await c.call('chat.send', { threadId: th.id, text: 'What model are you? Answer with only your exact model id, nothing else.' });
await done;
const { messages } = await c.call('bots.history', { id: bot.id, limit: 2 });
const m = messages.filter((x) => x.role === 'agent').at(-1);
log('reply:', m.parts.filter((p) => p.type === 'text').map((p) => p.text).join(''));
c.close(); process.exit(0);
