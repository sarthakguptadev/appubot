export class BotsService {
  constructor(private ctx: CoreCtx) {
    // instructions for every bot changed (Settings › Agents › Instructions): every bot's generated file follows, and its
    // agents restart with resume at their next turn (the rendered text is in the profile key)
    ctx.s.settings.onChange((next, prev) => {
      if (next.globalInstructions === prev.globalInstructions) return;
      for (const b of this.list()) this.scaffold(b, false);
    });
  }

  /** What `renderAgentInstructions` needs beyond the bot: where it runs, and the user's instructions for every bot. */
  instructionsOptions(bot?: Pick<Bot, 'memberId'>): InstructionsOptions {
    const language = languageName(this.ctx.deps.systemLanguage?.());
    // a cloud computer whose git was signed in to GitHub from the user's own computer: its bots are told (a team member's own home)
    const github = this.ctx.deps.cloud ? this.ctx.s.github?.signedInAs(bot ? this.ctx.s.logins.scopeOfBot(bot) : '') : undefined;
    // one of the user's own computers lends this one its files (`services/macFiles.ts`): the bots are told
    const mac = this.ctx.s.macFiles?.linkedName();
    return { ...(github ? { github } : {}), cloud: !!this.ctx.deps.cloud, global: this.ctx.store.settings.get().globalInstructions, ...(language ? { language } : {}), ...(mac ? { mac } : {}) };
  }

  /** Every bot's generated instructions written again (something they say changed: a computer linked or unlinked). */
  rescaffold(): void {
    for (const b of this.list()) this.scaffold(b, false);
  }

  list(): Bot[] { return this.ctx.store.bots.get(); }
  get(id: string): Bot | undefined { return this.list().find((b) => b.id === id); }
  require(id: string): Bot {
    const b = this.get(id);
    if (!b) throw notFound('Bot', id);
    return b;
  }

  /** Make sure the default bot exists (first run); existing bots get the current generated instructions. */
  ensureDefault(): void {
    if (this.list().length) {
      for (const b of this.list()) this.scaffold(b, false);
      return;
    }
    this.create({ ...DEFAULT_BOT, providerId: this.ctx.s.settings.get().defaultProviderId });
  }

  private uniqueSlug(name: string, exceptId?: string): string {
    const base = slugify(name);
    const taken = new Set(this.list().filter((b) => b.id !== exceptId).map((b) => b.slug));
    let slug = base;
    for (let i = 2; taken.has(slug) || (!exceptId && existsSync(join(this.ctx.paths.botsRoot, slug)) && this.isForeignDir(slug)); i++) slug = `${base}-${i}`;
    return slug;
  }

  /** A pre-existing folder that does not look like an AppuBot workspace (don't clobber it). */
  private isForeignDir(slug: string): boolean {
    const dir = join(this.ctx.paths.botsRoot, slug);
    return !existsSync(join(dir, 'MEMORY.md'));
  }

  /** `extra.memberId`: on a team's cloud computer, the person whose device (or bot) made it (§6.11) */
  create(p: MethodParams<'bots.create'>, extra: { memberId?: string } = {}): Bot {
    if (!cleanBotName(p.name ?? '')) throw new RpcError('invalid_params', 'Bot name is required');
    const now = Date.now();
    const slug = this.uniqueSlug(p.name);
    const look = randomLook();
    const st = this.ctx.s.settings.get();
    const providerId = p.providerId || st.defaultProviderId;
    // Settings' defaults: the effort always, the model only on the agent it belongs to; empty is the agent's own
    let modelId = p.modelId !== undefined ? p.modelId : providerId === st.defaultProviderId ? st.defaultModelId : '';
    // AppuBot AI (the launch bonus): Sonnet and Haiku, no fast mode; what was asked for is refused, a default left out
    checkCreditPick(providerId, { modelId: p.modelId, fast: p.fast });
    if (isAppubotAi(providerId) && modelId && !creditModelAllowed(modelId)) modelId = '';
    const bot = BotSchema.parse({
      ...p,
      ...(extra.memberId && this.ctx.deps.cloud ? { memberId: extra.memberId } : {}),
      color: p.color ?? look.color,
      shape: p.shape ?? look.shape,
      id: newId('bot'),
      slug,
      name: cleanBotName(p.name),
      providerId,
      modelId: modelId || undefined,
      effort: p.effort || st.defaultEffort,
      fast: isAppubotAi(providerId) ? false : p.fast ?? st.defaultFast,
      // Settings' default permission mode, as the agent's own (AppuBot's two choices on agents without levels of their own)
      modeId: toOfferedMode(providerId, p.modeId || st.defaultModeId || undefined),
      workspace: join(this.ctx.paths.botsRoot, slug),
      createdAt: now,
      updatedAt: now,
    });
    // a character from the library, or none
    if (!bot.characterId || !this.ctx.s.characters?.get(bot.characterId)) delete bot.characterId;
    this.scaffold(bot, true);
    this.ctx.store.bots.update((l) => [...l, bot]);
    this.ctx.bus.emit('bot.updated', bot);
    return bot;
  }

  update(id: string, patch: MethodParams<'bots.update'>['patch']): Bot {
    const prev = this.require(id);
    if (patch.name !== undefined && !cleanBotName(patch.name)) throw new RpcError('invalid_params', 'Bot name is required');
    const next = BotSchema.parse({ ...prev, ...patch, ...(patch.name !== undefined ? { name: cleanBotName(patch.name) } : {}), id, createdAt: prev.createdAt, updatedAt: Date.now() });
    // whose logins it runs on ('' takes the person off: an admin assigns it again); only a team's cloud computer sorts by person
    if (patch.memberId !== undefined && (!patch.memberId || !this.ctx.deps.cloud)) delete next.memberId;
    if (patch.memberId && !this.ctx.s.logins.members().some((m) => m.id === patch.memberId)) throw new RpcError('invalid_params', 'That person has no device on this computer');
    // a character from the library ('' takes it off: the bot wears its shape again)
    if (patch.characterId && !this.ctx.s.characters?.get(patch.characterId)) throw new RpcError('invalid_params', 'That character isn’t in the library any more');
    if (!next.characterId) delete next.characterId;
    // an empty model is the agent's own default; another agent doesn't have the old one's model
    if (patch.modelId === '' || (next.providerId !== prev.providerId && patch.modelId === undefined)) delete next.modelId;
    // AppuBot AI (the launch bonus): Sonnet and Haiku, no fast mode; a pick of anything else is refused, an old one dropped
    checkCreditPick(next.providerId, { modelId: patch.modelId, fast: patch.fast }, !!this.ctx.s.credit?.promo());
    if (isAppubotAi(next.providerId)) {
      if (next.modelId && !creditModelAllowed(next.modelId)) delete next.modelId;
      next.fast = false;
    }
    // the same choice (Approve for me, Full access) as the new agent's own ids (Claude Code's Auto is `auto`, Codex's
    // `agent`); empty is the agent's default (Full access on one with AppuBot's approvals)
    const moved = next.providerId !== prev.providerId && patch.modeId === undefined;
    const modeId = toOfferedMode(next.providerId, patch.modeId === '' ? undefined : moved ? permissionChoice(prev.providerId, prev.modeId) : next.modeId);
    if (modeId) next.modeId = modeId;
    else delete next.modeId;
    // workspace & slug are fixed after creation (renaming a bot keeps its folder)
    next.workspace = prev.workspace;
    next.slug = prev.slug;
    this.ctx.store.bots.update((l) => l.map((b) => (b.id === id ? next : b)));
    // the launch gift remembers what a bot used before it was put on the gift (services/promo.ts)
    if (next.providerId !== prev.providerId) this.ctx.s.promo?.botMoved(prev, next);
    // generated files follow the profile; a CLAUDE.md/AGENTS.md the user made their own stays theirs
    this.scaffold(next, false);
    this.ctx.bus.emit('bot.updated', next);
    // its agent settings apply to its threads: another provider continues each on a fresh, primed session; another
    // model, effort, fast mode or mode switches its current thread's (new threads start with the bot's own)
    if (next.providerId !== prev.providerId) {
      void this.ctx.s.chat.switchProvider(next).catch((e) => this.ctx.log.warn(`switching ${next.name} to ${next.providerId} failed`, String(e)));
    } else {
      const chat = currentChat(this.ctx.s.threads.list({ limit: 10_000 }), id);
      if (chat && next.modelId && next.modelId !== prev.modelId && next.modelId !== chat.modelId) {
        void this.ctx.s.chat.setModel(chat.id, next.modelId).catch((e) => this.ctx.log.warn(`setting the model of ${next.name} failed`, String(e)));
      }
      if (chat && next.effort !== prev.effort && next.effort !== chat.effortId) {
        void this.ctx.s.chat.setEffort(chat.id, next.effort).catch((e) => this.ctx.log.warn(`setting the effort of ${next.name} failed`, String(e)));
      }
      if (chat && next.fast !== prev.fast && next.fast !== chat.fast) {
        void this.ctx.s.chat.setFast(chat.id, next.fast).catch((e) => this.ctx.log.warn(`setting fast mode of ${next.name} failed`, String(e)));
      }
      if (chat && next.modeId && next.modeId !== prev.modeId && next.modeId !== chat.modeId) {
        void this.ctx.s.chat.setMode(chat.id, next.modeId).catch((e) => this.ctx.log.warn(`setting the mode of ${next.name} failed`, String(e)));
      }
    }
    return next;
  }

  async delete(id: string, deleteWorkspace: boolean): Promise<{ ok: true }> {
    const bot = this.require(id);
    for (const t of this.ctx.s.threads.list().filter((t) => t.botId === id)) await this.ctx.s.threads.delete(t.id).catch(() => undefined);
    for (const r of this.ctx.s.routines.list().filter((r) => r.botId === id)) this.ctx.s.routines.delete(r.id);
    this.ctx.store.bots.update((l) => l.filter((b) => b.id !== id));
    if (deleteWorkspace && bot.workspace.startsWith(this.ctx.paths.botsRoot)) rmSync(bot.workspace, { recursive: true, force: true });
    this.ctx.bus.emit('bot.deleted', { id });
    return { ok: true };
  }

  /**
   * Create the workspace layout; (re)generate CLAUDE.md/AGENTS.md (without \`regenerate\`: only missing or outdated
   * generated ones, never a file the user made their own); never touch MEMORY.md or skills.
   */
  scaffold(bot: Bot, regenerate: boolean): void {
    const ws = bot.workspace;
    try {
      for (const d of ['', 'inbox', 'outbox', '.claude/skills', '.agents']) mkdirSync(join(ws, d), { recursive: true });
      const link = join(ws, '.agents', 'skills');
      let linkExists = false;
      try { lstatSync(link); linkExists = true; } catch { /* missing */ }
      if (!linkExists) {
        // Windows: a junction (a directory symlink needs admin rights or Developer Mode there; a junction takes an
        // absolute target)
        try {
          if (process.platform === 'win32') symlinkSync(join(ws, '.claude', 'skills'), link, 'junction');
          else symlinkSync('../.claude/skills', link, 'dir');
        } catch (e) { this.ctx.log.warn('could not create .agents/skills symlink', String(e)); }
      }
      // the bot's memory is its own (and the user's): made when missing, never written over
      const memory = join(ws, MEMORY_FILE);
      if (!existsSync(memory)) writeFileSync(memory, memoryTemplate(bot.name));
      const instr = renderAgentInstructions(bot, this.instructionsOptions(bot));
      for (const f of ['CLAUDE.md', 'AGENTS.md']) {
        const p = join(ws, f);
        if (regenerate || !existsSync(p)) writeFileAtomic(p, instr);
        else {
          const cur = readFileSync(p, 'utf8');
          if (cur !== instr && cur.startsWith(GENERATED_MARK)) writeFileAtomic(p, instr);
        }
      }
    } catch (e) {
      this.ctx.log.error(`could not scaffold workspace ${ws}`, String(e));
    }
  }

  /* ------------------------------------------------------------- memory */

  memoryPath(id: string): string { return join(this.require(id).workspace, MEMORY_FILE); }

  private readMemory(bot: Bot): string {
    const path = join(bot.workspace, MEMORY_FILE);
    return existsSync(path) ? readFileSync(path, 'utf8') : '';
  }

  getMemory(id: string): { memory: string; path: string } {
    const bot = this.require(id);
    return { memory: this.readMemory(bot), path: join(bot.workspace, MEMORY_FILE) };
  }

  /** The whole memory (the bot editors); blank clears it to a fresh file. Running sessions keep what they have. */
  setMemory(id: string, memory: string): { ok: true } {
    const bot = this.require(id);
    writeFileAtomic(join(bot.workspace, MEMORY_FILE), memory.trim() ? memory : memoryTemplate(bot.name));
    return { ok: true };
  }

  /** What a fresh agent session's first prompt opens with: the bot's memory, capped (null while it holds nothing). */
  memoryPreface(bot: Bot): string | null {
    try { return memoryPreface(this.readMemory(bot), { botName: bot.name }); } catch (e) {
      this.ctx.log.warn(`could not read ${bot.name}'s memory`, String(e));
      return null;
    }
  }

  /** The memory as it stands (a fresh template when there is no file), for the bot's own tools. */
  readMemoryOf(id: string): MethodResult<'agent.memory.read'> {
    const bot = this.require(id);
    const memory = this.readMemory(bot) || memoryTemplate(bot.name);
    return { memory, path: join(bot.workspace, MEMORY_FILE), chars: memory.length };
  }

  private writeMemory(bot: Bot, memory: string): { path: string; chars: number } {
    const path = join(bot.workspace, MEMORY_FILE);
    writeFileAtomic(path, memory);
    return { path, chars: memory.length };
  }

  private entryText(text: string): string {
    const t = cleanEntry(text);
    if (t.length > MEMORY_ENTRY_MAX) throw new RpcError('invalid_params', `Too long for one memory (${t.length} characters, at most ${MEMORY_ENTRY_MAX}): save the gist, or a few short facts`);
    return t;
  }

  /** Adds a dated entry (`remember`), unless the memory already says it. */
  remember(id: string, text: string): MethodResult<'agent.remember'> {
    const bot = this.require(id);
    const t = this.entryText(text);
    if (!t) throw new RpcError('invalid_params', 'Nothing to remember');
    const r = appendMemory(this.readMemory(bot) || memoryTemplate(bot.name), t, todayStamp());
    if (!r.added) return { ok: true, path: join(bot.workspace, MEMORY_FILE), added: false, chars: r.memory.length };
    return { ok: true, added: true, ...this.writeMemory(bot, r.memory) };
  }

  /** Replaces the one entry containing `find` with `text` (dated), or removes it when `text` is empty. */
  updateMemory(id: string, find: string, text: string): MethodResult<'agent.memory.update'> {
    const bot = this.require(id);
    const r = replaceInMemory(this.readMemory(bot), find, this.entryText(text), todayStamp());
    if (!r.ok) {
      throw new RpcError('invalid_params', r.reason === 'none'
        ? `Nothing in your memory contains "${find}": read_memory shows what is there`
        : `${r.matches.length} entries contain "${find}"; quote more of the one to change:\n${r.matches.map((m) => `  ${m}`).join('\n')}`);
    }
    return { ok: true, removed: r.removed[0]!, ...(r.added ? { added: r.added } : {}), ...this.writeMemory(bot, r.memory) };
  }

  /** Removes every entry containing `text`. */
  forgetMemory(id: string, text: string): MethodResult<'agent.memory.forget'> {
    const bot = this.require(id);
    const r = forgetInMemory(this.readMemory(bot), text);
    if (!r.removed.length) throw new RpcError('invalid_params', `Nothing in your memory contains "${text}": read_memory shows what is there`);
    return { ok: true, removed: r.removed, ...this.writeMemory(bot, r.memory) };
  }
}
