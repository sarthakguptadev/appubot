/**
 * The bot's instructions (its CLAUDE.md, without the generated-file note) for an agent that doesn't read that file
 * (`readsInstructionFile`): they open the first message of each of its sessions, and come again after they change.
 */
export function renderInstructionsPreface(bot: Bot, changed: boolean, o: InstructionsOptions = {}): string {
  const text = renderAgentInstructions(bot, o).replace(/^<!--[^]*?-->\n/, '').trim();
  const lead = changed
    ? `[From AppuBot, not from the user: your instructions as ${bot.name} have changed. These replace the ones you were given before; follow them from now on.]`
    : `[From AppuBot, not from the user: your standing instructions as ${bot.name}. Your agent doesn't read CLAUDE.md or AGENTS.md by itself, so here they are: follow them for this whole conversation.]`;
  return `${lead}\n<instructions>\n${text}\n</instructions>`;
}

