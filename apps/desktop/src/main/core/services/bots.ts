/**
 * The hidden prompt of a new bot's first turn (\`ChatService.greet\`): the bot sets itself up in a short chat, the way
 * a person would on their first day (2026-11-17, the owner's ask: "it asks stuff to set itself up, like a chat for the
 * first time"). One question at a time on \`ask_user\` cards with suggested answers. A bot made from scratch asks what
 * it is for, one follow-up that fits that answer, what to call it while it still has a placeholder name, and anything it
 * should always or never do; a template (it has a job) asks a question or two to fit that job to this person. Then it
 * saves what it heard with its own tools (job, instructions, name, memory) and offers a first task. Those tools need no
 * approval in that turn (policy.ts \`SETUP_TOOLS\`), so Ask-permissions mode doesn't interrupt it.
 */
export function renderIntroPrompt(bot: Bot): string {
  const job = bot.job.trim();
  const unnamed = hasPlaceholderName(bot.name);
  const questions = job
    ? [
      `- One or two questions that fit your job (${job}) to them: what they want you to focus on first, and the specifics you need (which accounts, apps, places or people; how often; what matters most). Ask the second only if the first answer leaves something you need.`,
      unnamed && `- What to call you (your name is just "${bot.name}" for now). Suggest 3-4 short names that fit your job.`,
    ]
    : [
      `- What they'd like you for. Word it as "What should I help you with?" and suggest kinds of work you can do on their ${MACHINE} (for example: email and messages; research; files and documents; shopping and orders; work in one particular app).`,
      '- One follow-up that fits their answer, to learn how they want it done: which accounts, apps, folders or people; how often; what to watch for. Suggest answers that fit what they said.',
      unnamed && `- What to call you (your name is just "${bot.name}" for now). Suggest 3-4 short names that fit what they want you for.`,
      '- Anything you should always or never do. Suggest answers like "Ask before sending anything", "Keep answers short", "Check in every morning", "Nothing else".',
    ];
  const asks = questions.filter(Boolean);
  const saves = [
    unnamed && 'the name they picked',
    !job && 'your job (one short line)',
    job ? 'your instructions with a few short "- " lines added for what they told you (keep the lines already there)' : 'your instructions (2-5 short "- " lines in their words: what to do, how they like it, what never to do without asking)',
  ].filter(Boolean);
  const steps = [
    `Greet them as ${bot.name} in one short, warm sentence${job ? `, mentioning your job (${job})` : ''}, and say you'll ask a couple of quick things to set yourself up.`,
    `Ask these one at a time with the \`ask_user\` tool, each with 3-5 short suggested answers (they can also type their own). Wait for each answer before asking the next, and let what they said shape the next question. If they skip one or don't answer, use your best judgement and move on. Ask nothing beyond these:\n${asks.join('\n')}`,
    `Set yourself up from what they said: \`update_bot\` with ${saves.join(', and ')}; \`remember\` each lasting fact about them (one per call); \`save_skill\` only for a repeatable task they described step by step.`,
    'End with two or three short sentences: what you are set up to do now, and one concrete first task you could do for them right now. If they want something done regularly, offer to do it on a schedule.',
  ];
  return `[This message is from AppuBot, not from the user, and the user doesn't see it. The user just created you and hasn't written anything yet.]

Say hello and set yourself up with them, like a short first chat:
${steps.map((step, i) => `${i + 1}. ${step}`).join('\n')}

Use no tools other than these in this turn (no computer use, no files). Mention only what really got saved: the user may decline a tool call.`;
}

