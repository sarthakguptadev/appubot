/**
 * Moving a bot between computers (this Mac ↔ your AppuBot computer, either way, or any two AppuBot computers): one bot
 * packed into a zip ("bundle") of this computer's files (`bots.export`, handed out as `/files/<id>?download=1`), which
 * a device carries to the other computer (`POST /api/files`) and unpacks there (`bots.import`). What travels: the
 * bot's setup (name, look, job, instructions, agent, model, effort, mode, computer use, which apps are off), its
 * folder (memory, skills, inbox/outbox and the user's files; tool scratch like node_modules left out, the generated
 * CLAUDE.md/AGENTS.md remade on the other side), its routines, its chats with their messages and the files in them,
 * and the character it wears. What never travels: agent keys and logins, the Vault, connected apps' tokens, Telegram
 * tokens, the computer's identity and pairings; those stay with each computer and person, and the import lists what
 * to set up again by hand (`notes`). Chats come without their agent sessions (another computer can't resume them):
 * a thread goes on as a fresh session primed with its own recent turns, as any thread whose session is gone does.
 *
 * On a team's AppuBot computer the bot belongs to the person whose device imported it (`Bot.memberId`), so it runs on
 * their logins when the team uses "each person's own". A member may export only their own bots there.
 */
import { createWriteStream, existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { inflateRawSync } from 'node:zlib';
import { basename, dirname, join, normalize, sep } from 'node:path';
import { BotBundleManifestSchema, BotSchema, CharacterSchema, FileAttachmentSchema, MessageSchema, RoutineSchema, ThreadSchema, newId, type Bot, type BotBundleManifest, type BotExportInclude, type BotExportIncluded, type BotImportResult, type Character, type Exportable, type ExportableBot, type FileAttachment, type Message, type SharedSkill, type SharedSkillText, type Thread } from '@appubot/protocol';
import type { CoreCtx } from '../context';
import type { FileRecord } from '../store';
import { errMsg, RpcError } from '../util';
import { EXCLUDED_BOT_DIRS, ZipWriter, walk } from './cloudExport';
import { safeName } from './files';
import { parseSkillMd } from './skills';

/** the bundle's own name: `<slug>.appubot-bot.zip` */
export const BUNDLE_SUFFIX = '.appubot-bot.zip';
/** generated instruction files are remade on the other side (`BotsService.scaffold`) */
const GENERATED_MARK = '<!-- Generated by AppuBot.';
const INSTRUCTION_FILES = new Set(['CLAUDE.md', 'AGENTS.md']);
/** a bundle entry (its uncompressed bytes) or a bundle past this is refused: a bot, not a disk image */
const ENTRY_MAX = 2 * 1024 * 1024 * 1024;
const BUNDLE_MAX = 8 * 1024 * 1024 * 1024;
/** a shared skill's folder past this (a skill, not a project) is left out of a transfer */
const SHARED_SKILL_MAX = 50 * 1024 * 1024;
/** where the person's own skills for every agent live, under their home, first of a name wins */
const SHARED_SKILL_DIRS: { from: SharedSkill['from']; dir: string[] }[] = [
  { from: 'claude', dir: ['.claude', 'skills'] },
  { from: 'agents', dir: ['.agents', 'skills'] },
  { from: 'codex', dir: ['.codex', 'skills'] },
];
const SKILLS_PREFIX = '.claude/skills/';

/** which part of a bot's folder a file (relative, `/`) belongs to; null = never packed (the generated instructions) */
export function workspacePart(rel: string): 'memory' | 'skills' | 'files' {
  if (rel === 'MEMORY.md') return 'memory';
  if (rel.startsWith(SKILLS_PREFIX)) return 'skills';
  return 'files';
}

/** every part on unless switched off (the Move dialog sends none) */
export function resolveInclude(include?: BotExportInclude): Omit<BotExportIncluded, 'sharedSkills'> {
  return { memory: include?.memory !== false, skills: include?.skills !== false, files: include?.files !== false, routines: include?.routines !== false, chats: include?.chats !== false };
}

interface BundleBot { name: string; emoji?: string; color: string; shape: string; job: string; instructions: string; providerId: string; modelId?: string; modeId?: string; effort: string; fast: boolean; computerUse: boolean; appsOff: string[]; pinned: boolean }
interface BundleFile { id: string; name: string; mimeType: string; size: number; threadId?: string; createdAt: number; entry: string }

export class BotBundleService {
  constructor(private ctx: CoreCtx) {}

  /* ---------------------------------------------------------------- export */

  /** Packs one bot into a bundle of this computer's files. `member`: on a team's computer, who asks (their own bots only). */
  async export(botId: string, member?: string, opts: { include?: BotExportInclude; sharedSkills?: string[] } = {}): Promise<{ file: FileAttachment; manifest: BotBundleManifest; included: BotExportIncluded }> {
    const bot = this.ctx.s.bots.require(botId);
    const inc = resolveInclude(opts.include);
    // shared skills come only from this computer's own list, by name (never a path a caller names)
    const shared = opts.sharedSkills?.length ? this.sharedSkillDirs().filter((x) => opts.sharedSkills!.includes(x.skill.name)) : [];
    if (member && bot.memberId && bot.memberId !== member) throw new RpcError('forbidden', 'Only the person whose bot this is (or an admin) can move it.');
    const { paths } = this.ctx;
    // the previous bundle of this bot goes: the new one replaces it
    for (const rec of this.ctx.store.files.get()) {
      if (rec.name === `${bot.slug}${BUNDLE_SUFFIX}` && !rec.threadId) {
        try { rmSync(join(paths.filesDir, rec.id), { recursive: true, force: true }); } catch { /* gone */ }
        this.ctx.store.files.update((l) => l.filter((f) => f.id !== rec.id));
      }
    }
    const id = newId('file');
    const name = `${bot.slug}${BUNDLE_SUFFIX}`;
    const dir = join(paths.filesDir, id);
    mkdirSync(dir, { recursive: true });
    const storedPath = join(dir, name);
    const zip = new ZipWriter(createWriteStream(storedPath));
    const counts = { threads: 0, messages: 0, routines: 0, skills: 0, files: 0, workspaceFiles: 0, bytes: 0 };
    try {
      // the bot's setup
      const fields: BundleBot = {
        name: bot.name, emoji: bot.emoji, color: bot.color, shape: bot.shape, job: bot.job, instructions: bot.instructions, providerId: bot.providerId,
        ...(bot.modelId ? { modelId: bot.modelId } : {}), ...(bot.modeId ? { modeId: bot.modeId } : {}), effort: bot.effort, fast: bot.fast,
        computerUse: bot.computerUse, appsOff: bot.appsOff, pinned: bot.pinned,
      };
      await zip.bytes('bot.json', Buffer.from(JSON.stringify(fields, null, 2)));
      const character = this.ctx.s.characters?.get(bot.characterId);
      if (character) await zip.bytes('character.json', Buffer.from(JSON.stringify(character, null, 2)));
      // its folder: memory, skills, inbox and outbox, the user's own files; scratch and generated instructions left out
      const ownSkills = new Set<string>();
      if (existsSync(bot.workspace)) {
        for (const f of walk(bot.workspace, (abs, rel, isDir) => (isDir ? !EXCLUDED_BOT_DIRS.has(basename(abs)) : !(rel.split('/').length === 1 && INSTRUCTION_FILES.has(rel) && isGenerated(abs)) && !rel.endsWith(BUNDLE_SUFFIX)))) {
          if (f.st.size >= ENTRY_MAX) continue;
          if (!inc[workspacePart(f.rel)]) continue;
          await zip.file(`workspace/${f.rel}`, f.abs, f.st);
          counts.workspaceFiles++;
          counts.bytes += f.st.size;
          if (f.rel.startsWith(SKILLS_PREFIX) && basename(f.rel) === 'SKILL.md') { counts.skills++; ownSkills.add(f.rel.split('/')[2]!); }
        }
      }
      // shared skills picked to go with it, beside its own (its own win a clash)
      const sharedAdded: string[] = [];
      for (const { skill, dir: skillDir } of shared) {
        if (ownSkills.has(skill.name)) continue;
        for (const f of walk(skillDir, (abs, _rel, isDir) => !isDir || !EXCLUDED_BOT_DIRS.has(basename(abs)))) {
          await zip.file(`workspace/${SKILLS_PREFIX}${skill.name}/${f.rel}`, f.abs, f.st);
          counts.workspaceFiles++;
          counts.bytes += f.st.size;
        }
        counts.skills++;
        sharedAdded.push(skill.name);
      }
      // routines
      const routines = inc.routines ? this.ctx.s.routines.list().filter((r) => r.botId === bot.id) : [];
      await zip.bytes('routines.json', Buffer.from(JSON.stringify(routines, null, 2)));
      counts.routines = routines.length;
      // chats, whole, and the files in them
      const fileIds = new Set<string>();
      const threads = inc.chats ? this.ctx.s.threads.list({ limit: 100_000 }).filter((t) => t.botId === bot.id) : [];
      for (const t of threads) {
        const messages = this.ctx.store.threads.allMessages(t.id);
        await zip.bytes(`threads/${t.id}.json`, Buffer.from(JSON.stringify({ thread: t, messages })));
        counts.threads++;
        counts.messages += messages.length;
        for (const m of messages) for (const fid of fileIdsIn(m)) fileIds.add(fid);
      }
      const threadIds = new Set(threads.map((t) => t.id));
      const files: BundleFile[] = [];
      for (const rec of this.ctx.store.files.get()) {
        if (!(fileIds.has(rec.id) || (rec.threadId && threadIds.has(rec.threadId)))) continue;
        let st;
        try { st = statSync(rec.storedPath); } catch { continue; }
        if (!st.isFile() || st.size >= ENTRY_MAX) continue;
        const entry = `files/${rec.id}/${safeName(rec.name)}`;
        await zip.file(entry, rec.storedPath, st);
        files.push({ id: rec.id, name: rec.name, mimeType: rec.mimeType, size: rec.size, ...(rec.threadId ? { threadId: rec.threadId } : {}), createdAt: rec.createdAt, entry });
        counts.files++;
        counts.bytes += st.size;
      }
      await zip.bytes('files.json', Buffer.from(JSON.stringify(files, null, 2)));
      // the Telegram bot it answered as, by handle only
      const channel = this.ctx.s.channels.list().find((c) => (c.botId ?? this.ctx.s.bots.list()[0]?.id) === bot.id && c.botUsername);
      const apps = this.appsOf(bot);
      const manifest: BotBundleManifest = BotBundleManifestSchema.parse({
        version: 1, exportedAt: Date.now(),
        from: { hostName: this.ctx.deps.hostName, platform: process.platform, cloud: !!this.ctx.deps.cloud, version: this.ctx.deps.version },
        bot: { name: bot.name, job: bot.job, color: bot.color, shape: bot.shape, providerId: bot.providerId, ...(bot.modelId ? { modelId: bot.modelId } : {}), effort: bot.effort, computerUse: bot.computerUse, ...(character ? { characterName: character.name } : {}) },
        counts, ...(channel?.botUsername ? { telegram: { handle: channel.botUsername.replace(/^@/, '') } } : {}), apps,
      });
      await zip.bytes('manifest.json', Buffer.from(JSON.stringify(manifest, null, 2)));
      await zip.bytes('README.txt', Buffer.from([
        `AppuBot bot bundle: ${bot.name}, from ${this.ctx.deps.hostName}, ${new Date().toISOString()}`, '',
        'Open it in AppuBot on another computer (the bot’s menu → Move) to carry the bot over.', '',
        'bot.json       its setup   workspace/   its folder (memory, skills, files)   routines.json   threads/   its chats   files/   the chats’ files',
        'Left out on purpose: agent keys and logins, the Vault, connected apps’ tokens, Telegram tokens.', '',
      ].join('\n')));
      await zip.finish();
      const rec: FileRecord = { id, name, mimeType: 'application/zip', size: statSync(storedPath).size, url: `/files/${id}`, storedPath, createdAt: Date.now() };
      this.ctx.store.files.update((l) => [...l, rec]);
      this.ctx.store.files.flush();
      const att = this.ctx.s.files.toAttachment(rec);
      this.ctx.bus.emit('file.created', att);
      this.ctx.log.info(`bot bundle: ${bot.name} packed, ${counts.threads} chats, ${counts.files} files, ${rec.size} bytes`);
      return { file: att, manifest, included: { ...inc, sharedSkills: sharedAdded } };
    } catch (e) {
      try { rmSync(dir, { recursive: true, force: true }); } catch { /* ignore */ }
      if (e instanceof RpcError) throw e;
      throw new RpcError('internal', `Packing the bot failed: ${errMsg(e)}`);
    }
  }

  /* ------------------------------------------------------- what a transfer could carry */

  /** Every bot here, part by part with its size, and the shared skills (Settings › Transfer on another computer). */
  exportable(member?: string): Exportable {
    const records = this.ctx.store.files.get();
    const bots: ExportableBot[] = [];
    for (const bot of this.ctx.s.bots.list()) {
      if (member && bot.memberId && bot.memberId !== member) continue;
      const parts = { memory: 0, skills: 0, files: 0, fileCount: 0 };
      const skillNames = new Set<string>();
      if (existsSync(bot.workspace)) {
        for (const f of walk(bot.workspace, (abs, rel, isDir) => (isDir ? !EXCLUDED_BOT_DIRS.has(basename(abs)) : !(rel.split('/').length === 1 && INSTRUCTION_FILES.has(rel)) && !rel.endsWith(BUNDLE_SUFFIX)))) {
          if (f.st.size >= ENTRY_MAX) continue;
          const part = workspacePart(f.rel);
          if (part === 'memory') parts.memory += f.st.size;
          else if (part === 'skills') {
            parts.skills += f.st.size;
            if (basename(f.rel) === 'SKILL.md' && f.rel.split('/').length === 4) skillNames.add(f.rel.split('/')[2]!);
          } else { parts.files += f.st.size; parts.fileCount++; }
        }
      }
      const threads = this.ctx.s.threads.list({ limit: 100_000 }).filter((t) => t.botId === bot.id);
      const threadIds = new Set(threads.map((t) => t.id));
      let chatBytes = 0;
      let messages = 0;
      for (const t of threads) {
        chatBytes += this.ctx.store.threads.diskBytes(t.id);
        messages += this.ctx.store.threads.getMessages(t.id).length + this.ctx.store.threads.archiveRefs(t.id).reduce((n, r) => n + r.count, 0);
      }
      // the files in its chats (those a message names elsewhere are rare: counted when the bundle is made)
      for (const rec of records) if (rec.threadId && threadIds.has(rec.threadId)) chatBytes += rec.size;
      const character = this.ctx.s.characters?.get(bot.characterId);
      bots.push({
        bot, ...(character ? { character } : {}),
        memory: { bytes: parts.memory },
        skills: { names: [...skillNames].sort(), bytes: parts.skills },
        files: { count: parts.fileCount, bytes: parts.files },
        routines: { count: this.ctx.s.routines.list().filter((r) => r.botId === bot.id).length },
        chats: { threads: threads.length, messages, bytes: chatBytes },
      });
    }
    return { hostName: this.ctx.deps.hostName, bots, sharedSkills: this.sharedSkillDirs().map((x) => x.skill) };
  }

  /** The person's own skills for every agent here (`~/.claude/skills`, `~/.agents/skills`, `~/.codex/skills`), with where each is. */
  private sharedSkillDirs(): { skill: SharedSkill; dir: string }[] {
    const home = this.ctx.deps.homeDir ?? homedir();
    const out: { skill: SharedSkill; dir: string }[] = [];
    const seen = new Set<string>();
    for (const { from, dir } of SHARED_SKILL_DIRS) {
      const root = join(home, ...dir);
      let names: string[];
      try { names = readdirSync(root).sort(); } catch { continue; }
      for (const name of names) {
        if (seen.has(name) || name.startsWith('.') || !/^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/.test(name)) continue;
        // a skill is often a link to where its maker keeps it: followed for the folder itself, never inside it
        let real: string;
        try { real = realpathSync(join(root, name)); if (!statSync(real).isDirectory()) continue; } catch { continue; }
        const md = join(real, 'SKILL.md');
        let raw: string;
        try { raw = readFileSync(md, 'utf8'); } catch { continue; }
        let files = 0, bytes = 0;
        for (const f of walk(real, (abs, _rel, isDir) => !isDir || !EXCLUDED_BOT_DIRS.has(basename(abs)))) { files++; bytes += f.st.size; if (bytes > SHARED_SKILL_MAX) break; }
        if (bytes > SHARED_SKILL_MAX) continue;
        seen.add(name);
        out.push({ skill: { name, description: parseSkillMd(raw).description, from, files, bytes }, dir: real });
      }
    }
    return out;
  }

  /** One shared skill's SKILL.md (Settings › Transfer gives it to bots already on the other computer). */
  sharedSkill(name: string): SharedSkillText {
    const found = this.sharedSkillDirs().find((x) => x.skill.name === name);
    if (!found) throw new RpcError('not_found', `There’s no shared skill “${name}” on this computer.`);
    const p = parseSkillMd(readFileSync(join(found.dir, 'SKILL.md'), 'utf8'));
    return { name, description: p.description || name, body: p.body.trim(), files: found.skill.files };
  }

  /** the apps (Composio toolkit slugs) this bot had on, by name only */
  private appsOf(bot: Bot): string[] {
    try {
      const connected = this.ctx.s.composioFor(this.ctx.s.logins.scopeOfBot(bot)).connectedSlugs();
      return connected.filter((slug) => !bot.appsOff.includes(slug));
    } catch { return []; }
  }

  /* ---------------------------------------------------------------- import */

  /**
   * Unpacks a bundle uploaded to this computer (`fileId`) into a new bot here. `member`: on a team's computer, the
   * person whose device asks (the bot becomes theirs).
   */
  async import(o: { fileId: string; name?: string; routines?: boolean; member?: string }): Promise<BotImportResult> {
    const rec = this.ctx.s.files.getRecord(o.fileId);
    if (!rec) throw new RpcError('not_found', 'That bundle isn’t on this computer (upload it first).');
    if (rec.size > BUNDLE_MAX) throw new RpcError('invalid_params', 'That bundle is too large to be a bot.');
    let zip: ZipReader;
    try { zip = new ZipReader(readFileSync(rec.storedPath)); } catch (e) { throw new RpcError('invalid_params', `That isn’t a bot bundle: ${errMsg(e)}`); }
    const json = <T>(entry: string): T | undefined => { const b = zip.read(entry); return b ? (JSON.parse(b.toString('utf8')) as T) : undefined; };
    const manifest = BotBundleManifestSchema.safeParse(json('manifest.json'));
    const fields = json<BundleBot>('bot.json');
    if (!manifest.success || !fields || typeof fields.name !== 'string') throw new RpcError('invalid_params', 'That isn’t a bot bundle (no manifest).');
    const notes: string[] = [];
    // the agent: the same one when this computer has it, else the default here
    const providers = this.ctx.s.providers.list();
    let providerId = fields.providerId;
    const agent = providers.find((p) => p.id === providerId);
    const agentName = (id: string) => providers.find((p) => p.id === id)?.name ?? id;
    if (!agent) {
      providerId = this.ctx.s.settings.get().defaultProviderId;
      notes.push(`It used ${agentName(fields.providerId)} there, which this computer doesn’t have: it runs on ${agentName(providerId)} here. Change it in its settings.`);
    } else if (!agent.installed) notes.push(`Install ${agent.name} here (Settings › Agents): the bot runs on it.`);
    else if (agent.authStatus === 'needs_auth') notes.push(`Sign in to ${agent.name} here (Settings › Agents): logins stay with each computer.`);
    const bot = this.ctx.s.bots.create({
      name: o.name?.trim() || fields.name, emoji: fields.emoji, color: fields.color, shape: BotSchema.shape.shape.safeParse(fields.shape).success ? (fields.shape as Bot['shape']) : undefined,
      job: fields.job ?? '', instructions: fields.instructions ?? '', providerId,
      ...(agent && fields.modelId ? { modelId: fields.modelId } : {}), ...(agent && fields.modeId ? { modeId: fields.modeId } : {}),
      effort: fields.effort, fast: fields.fast, computerUse: !!fields.computerUse, appsOff: Array.isArray(fields.appsOff) ? fields.appsOff : [],
    }, { ...(o.member ? { memberId: o.member } : {}) });
    const counts = { threads: 0, messages: 0, routines: 0, skills: 0, files: 0 };
    try {
      // its folder, under its new home only (a bundle names nothing outside it)
      for (const e of zip.entries()) {
        if (!e.name.startsWith('workspace/') || e.name.endsWith('/')) continue;
        const rel = safeRelative(e.name.slice('workspace/'.length));
        if (!rel) continue;
        if (rel.split('/').length === 1 && INSTRUCTION_FILES.has(rel)) continue;
        const data = zip.read(e.name);
        if (!data) continue;
        const dest = join(bot.workspace, ...rel.split('/'));
        mkdirSync(dirname(dest), { recursive: true });
        writeFileSync(dest, data);
        if (rel.startsWith('.claude/skills/') && basename(rel) === 'SKILL.md') counts.skills++;
      }
      // the character it wore, into this computer's library (by name, once)
      const character = json<Character>('character.json');
      if (character && this.ctx.s.characters) {
        const c = CharacterSchema.safeParse(character);
        if (c.success) {
          const have = this.ctx.s.characters.list().find((x) => x.name === c.data.name && x.body === c.data.body)
            ?? this.ctx.s.characters.save({ name: c.data.name, body: c.data.body, face: c.data.face, source: c.data.source });
          this.ctx.s.bots.update(bot.id, { characterId: have.id });
        }
      }
      if (fields.pinned) this.ctx.s.bots.update(bot.id, { pinned: true });
      // the chats' files, then the chats with the files' new ids in them
      const fileMap = new Map<string, FileAttachment>();
      const files = json<BundleFile[]>('files.json') ?? [];
      const threadMap = new Map<string, string>();
      for (const e of zip.entries()) if (e.name.startsWith('threads/') && e.name.endsWith('.json')) threadMap.set(basename(e.name, '.json'), newId('thread'));
      for (const f of Array.isArray(files) ? files : []) {
        const data = typeof f.entry === 'string' && f.entry.startsWith('files/') ? zip.read(f.entry) : undefined;
        if (!data) continue;
        const att = this.ctx.s.files.upload(data, f.name, f.mimeType, f.threadId ? threadMap.get(f.threadId) : undefined);
        fileMap.set(f.id, att);
        counts.files++;
      }
      for (const [oldId, id] of threadMap) {
        const tf = json<{ thread: unknown; messages: unknown[] }>(`threads/${oldId}.json`);
        const t = ThreadSchema.safeParse(tf?.thread);
        if (!t.success) continue;
        const thread: Thread = {
          ...t.data, id, botId: bot.id, cwd: bot.workspace, providerId, status: 'idle', acpSessionId: undefined, routineId: undefined, channel: undefined,
          ...(agent ? {} : { modelId: undefined, modeId: undefined, efforts: [], models: [], modes: [], effortId: undefined }),
        };
        delete thread.acpSessionId;
        delete thread.routineId;
        delete thread.channel;
        const messages = (Array.isArray(tf?.messages) ? tf!.messages : []).flatMap((raw) => {
          const m = MessageSchema.safeParse(remapIds(raw, fileMap, threadMap));
          return m.success ? [{ ...m.data, id: newId('msg'), threadId: id, ...(m.data.status === 'streaming' ? { status: 'cancelled' as const } : {}) }] : [];
        });
        this.ctx.store.threads.put(thread);
        this.ctx.store.threads.setMessages(id, messages);
        this.ctx.bus.emit('thread.updated', thread);
        counts.threads++;
        counts.messages += messages.length;
      }
      // routines
      for (const raw of json<unknown[]>('routines.json') ?? []) {
        const r = RoutineSchema.safeParse(raw);
        if (!r.success) continue;
        try {
          this.ctx.s.routines.create({ botId: bot.id, name: r.data.name, prompt: r.data.prompt, schedule: r.data.schedule, enabled: o.routines === false ? false : r.data.enabled, deliverTo: r.data.deliverTo });
          counts.routines++;
        } catch (e) { notes.push(`The routine “${r.data.name}” couldn’t be set up here: ${errMsg(e)}`); }
      }
      if (counts.routines && o.routines === false) notes.push('Its routines are here but off: turn them on when this computer should run them.');
      const m = manifest.data;
      if (m.telegram) notes.push(`On Telegram it answered as @${m.telegram.handle} there. To move that too, disconnect it there and connect it here (Settings › Channels).`);
      if (m.apps.length) notes.push(`It used ${listWords(m.apps)} there. Apps connect per computer and person: connect ${m.apps.length === 1 ? 'it' : 'them'} here (Apps) for it to keep using ${m.apps.length === 1 ? 'it' : 'them'}.`);
      if (m.from.cloud !== !!this.ctx.deps.cloud) notes.push('The Vault’s logins and the agents’ keys stayed where they were: they never travel.');
      this.ctx.bus.emit('bot.updated', this.ctx.s.bots.require(bot.id));
      this.ctx.store.flush();
      this.ctx.log.info(`bot bundle: ${bot.name} unpacked, ${counts.threads} chats, ${counts.messages} messages, ${counts.files} files, ${counts.routines} routines`);
      return { bot: this.ctx.s.bots.require(bot.id), manifest: m, notes, counts };
    } catch (e) {
      // half a bot is worse than none
      await this.ctx.s.bots.delete(bot.id, true).catch(() => undefined);
      if (e instanceof RpcError) throw e;
      throw new RpcError('internal', `Unpacking the bot failed: ${errMsg(e)}`);
    } finally {
      // the uploaded bundle is scratch once read
      try { rmSync(join(this.ctx.paths.filesDir, rec.id), { recursive: true, force: true }); } catch { /* ignore */ }
      this.ctx.store.files.update((l) => l.filter((f) => f.id !== rec.id));
    }
  }
}

/* -------------------------------------------------------------- helpers */

function isGenerated(abs: string): boolean {
  try { return readFileSync(abs, 'utf8').startsWith(GENERATED_MARK); } catch { return false; }
}

/** a bundle path kept inside the bot's folder: no absolute path, no `..`, no backslash tricks; '' when it isn't */
export function safeRelative(rel: string): string {
  if (!rel || rel.includes('\0') || rel.includes('\\')) return '';
  const n = normalize(rel).split(sep).join('/');
  if (n.startsWith('/') || n === '..' || n.startsWith('../') || n.includes('/../') || /^[a-zA-Z]:/.test(n)) return '';
  return n;
}

/** the ids of this computer's files a message refers to (`/files/<id>` in its parts) */
export function fileIdsIn(m: Message): string[] {
  const out = new Set<string>();
  for (const match of JSON.stringify(m.parts).matchAll(/\/files\/(file_[A-Za-z0-9_-]+)/g)) out.add(match[1]!);
  return [...out];
}

/** a message's JSON with the files' and threads' old ids swapped for their new ones */
function remapIds(raw: unknown, files: Map<string, FileAttachment>, threads: Map<string, string>): unknown {
  let json = JSON.stringify(raw);
  for (const [oldId, att] of files) json = json.split(oldId).join(att.id);
  for (const [oldId, id] of threads) json = json.split(oldId).join(id);
  return JSON.parse(json);
}

function listWords(items: string[]): string {
  if (items.length <= 1) return items.join('');
  return `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`;
}

/* ------------------------------------------------------------ zip reading */

interface ZipEntry { name: string; method: number; csize: number; size: number; offset: number }

/** A plain zip in memory (what `ZipWriter` writes, or any ordinary one): the central directory, then entries by name. */
export class ZipReader {
  private byName = new Map<string, ZipEntry>();

  constructor(private buf: Buffer) {
    const end = findEocd(buf);
    if (end < 0) throw new Error('not a zip file');
    const count = buf.readUInt16LE(end + 10);
    const dirSize = buf.readUInt32LE(end + 12);
    const dirAt = buf.readUInt32LE(end + 16);
    if (count === 0xffff || dirSize === 0xffff_ffff || dirAt === 0xffff_ffff) throw new Error('a ZIP64 archive: too large for a bot bundle');
    let at = dirAt;
    for (let i = 0; i < count; i++) {
      if (at + 46 > buf.length || buf.readUInt32LE(at) !== 0x02014b50) throw new Error('a damaged zip');
      const method = buf.readUInt16LE(at + 10);
      const csize = buf.readUInt32LE(at + 20);
      const size = buf.readUInt32LE(at + 24);
      const nameLen = buf.readUInt16LE(at + 28), extraLen = buf.readUInt16LE(at + 30), commentLen = buf.readUInt16LE(at + 32);
      const offset = buf.readUInt32LE(at + 42);
      const name = buf.toString('utf8', at + 46, at + 46 + nameLen);
      this.byName.set(name, { name, method, csize, size, offset });
      at += 46 + nameLen + extraLen + commentLen;
    }
  }

  entries(): ZipEntry[] { return [...this.byName.values()]; }

  /** an entry's bytes, or undefined when there's no such entry */
  read(name: string): Buffer | undefined {
    const e = this.byName.get(name);
    if (!e) return undefined;
    const h = e.offset;
    if (h + 30 > this.buf.length || this.buf.readUInt32LE(h) !== 0x04034b50) throw new Error(`a damaged zip entry: ${name}`);
    const nameLen = this.buf.readUInt16LE(h + 26), extraLen = this.buf.readUInt16LE(h + 28);
    const start = h + 30 + nameLen + extraLen;
    const raw = this.buf.subarray(start, start + e.csize);
    if (e.method === 0) return Buffer.from(raw);
    if (e.method === 8) {
      const out = inflateRawSync(raw, { maxOutputLength: ENTRY_MAX });
      if (out.length !== e.size) throw new Error(`a damaged zip entry: ${name}`);
      return out;
    }
    throw new Error(`an unsupported zip method ${e.method} in ${name}`);
  }
}

/** where the end-of-central-directory record starts (searched back through the comment's room), or -1 */
function findEocd(buf: Buffer): number {
  const min = Math.max(0, buf.length - 22 - 0xffff);
  for (let i = buf.length - 22; i >= min; i--) if (buf.readUInt32LE(i) === 0x06054b50) return i;
  return -1;
}

